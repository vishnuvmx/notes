/// Supported Mermaid diagram types.
enum MermaidDiagramType {
  flowchart,
  pie,
  sequence,
  unsupported,
}

/// Shape types for flowchart nodes.
enum MermaidNodeShape {
  process,   // [text]
  rounded,   // (text)
  pill,      // ([text])
  decision,  // {text}
  database,  // [(text)]
  circle,    // ((text))
}

/// Parsed node in a flowchart graph.
class MermaidNode {
  final String id;
  final String label;
  final MermaidNodeShape shape;

  const MermaidNode({
    required this.id,
    required this.label,
    this.shape = MermaidNodeShape.process,
  });
}

/// Parsed edge/connector in a flowchart graph.
class MermaidEdge {
  final String fromId;
  final String toId;
  final String? label;
  final bool isDotted;
  final bool isThick;

  const MermaidEdge({
    required this.fromId,
    required this.toId,
    this.label,
    this.isDotted = false,
    this.isThick = false,
  });
}

/// Parsed slice for pie charts.
class MermaidPieSlice {
  final String label;
  final double value;

  const MermaidPieSlice({
    required this.label,
    required this.value,
  });
}

/// Parsed message in sequence diagrams.
class MermaidSequenceMessage {
  final String from;
  final String to;
  final String text;
  final bool isDashed;

  const MermaidSequenceMessage({
    required this.from,
    required this.to,
    required this.text,
    this.isDashed = false,
  });
}

/// Result of parsing a Mermaid code block.
class ParsedMermaidDiagram {
  final MermaidDiagramType type;
  final String rawCode;
  final String? title;
  final String direction; // 'TD', 'TB', 'LR', 'RL', 'BT'
  final List<MermaidNode> nodes;
  final List<MermaidEdge> edges;
  final List<MermaidPieSlice> pieSlices;
  final List<String> participants;
  final List<MermaidSequenceMessage> sequenceMessages;
  final String? parseError;

  const ParsedMermaidDiagram({
    required this.type,
    required this.rawCode,
    this.title,
    this.direction = 'TD',
    this.nodes = const [],
    this.edges = const [],
    this.pieSlices = const [],
    this.participants = const [],
    this.sequenceMessages = const [],
    this.parseError,
  });

  bool get isValid => parseError == null && type != MermaidDiagramType.unsupported;
}

/// Lightweight, pure Dart parser for common Mermaid diagram syntaxes
/// generated by Antigravity, LLMs, and markdown authors.
class MermaidDiagramParser {
  MermaidDiagramParser._();

  static ParsedMermaidDiagram parse(String rawCode) {
    final cleanCode = rawCode.trim();
    if (cleanCode.isEmpty) {
      return ParsedMermaidDiagram(
        type: MermaidDiagramType.unsupported,
        rawCode: rawCode,
        parseError: 'Empty diagram content',
      );
    }

    final lines = cleanCode
        .split('\n')
        .map((l) => l.trim())
        .where((l) => l.isNotEmpty && !l.startsWith('%%'))
        .toList();

    if (lines.isEmpty) {
      return ParsedMermaidDiagram(
        type: MermaidDiagramType.unsupported,
        rawCode: rawCode,
        parseError: 'No active diagram statements',
      );
    }

    final firstLine = lines.first.toLowerCase();

    // 1. Pie Chart: pie [title ...]
    if (firstLine.startsWith('pie')) {
      return _parsePieChart(rawCode, lines);
    }

    // 2. Sequence Diagram: sequenceDiagram
    if (firstLine.startsWith('sequencediagram')) {
      return _parseSequenceDiagram(rawCode, lines);
    }

    // 3. Flowchart / Graph: graph TD / flowchart LR ...
    if (firstLine.startsWith('graph') || firstLine.startsWith('flowchart')) {
      return _parseFlowchart(rawCode, lines);
    }

    // Fallback: If lines contain '-->' or '---', attempt flowchart parsing
    if (lines.any((l) => l.contains('-->') || l.contains('---') || l.contains('==>'))) {
      return _parseFlowchart(rawCode, lines);
    }

    return ParsedMermaidDiagram(
      type: MermaidDiagramType.unsupported,
      rawCode: rawCode,
      parseError: 'Unsupported or unrecognized Mermaid diagram type',
    );
  }

  static ParsedMermaidDiagram _parsePieChart(String rawCode, List<String> lines) {
    String? title;
    final slices = <MermaidPieSlice>[];

    final quoteStripRegex = RegExp(r'^["\x27]|["\x27]$');
    final sliceRegex = RegExp(r'^["\x27]?(.*?)["\x27]?\s*:\s*([\d.]+)');

    for (int i = 0; i < lines.length; i++) {
      final line = lines[i];
      if (line.toLowerCase().startsWith('pie')) {
        // Check for 'pie title <Title>' or 'title <Title>'
        final titleMatch = RegExp(r'title\s+([^\n\r]+)', caseSensitive: false).firstMatch(line);
        if (titleMatch != null) {
          title = titleMatch.group(1)?.replaceAll(quoteStripRegex, '').trim();
        }
        continue;
      }

      if (line.toLowerCase().startsWith('title ')) {
        title = line.substring(6).replaceAll(quoteStripRegex, '').trim();
        continue;
      }

      // Slice: "Label" : 42 or Label: 42
      final sliceMatch = sliceRegex.firstMatch(line);
      if (sliceMatch != null) {
        final label = sliceMatch.group(1)?.trim() ?? 'Item';
        final val = double.tryParse(sliceMatch.group(2) ?? '0') ?? 0.0;
        if (val > 0) {
          slices.add(MermaidPieSlice(label: label, value: val));
        }
      }
    }

    if (slices.isEmpty) {
      return ParsedMermaidDiagram(
        type: MermaidDiagramType.pie,
        rawCode: rawCode,
        parseError: 'No data slices found in pie chart',
      );
    }

    return ParsedMermaidDiagram(
      type: MermaidDiagramType.pie,
      rawCode: rawCode,
      title: title,
      pieSlices: slices,
    );
  }

  static ParsedMermaidDiagram _parseSequenceDiagram(String rawCode, List<String> lines) {
    final participants = <String>{};
    final messages = <MermaidSequenceMessage>[];
    String? title;

    for (int i = 0; i < lines.length; i++) {
      final line = lines[i];
      if (line.toLowerCase().startsWith('sequencediagram')) continue;
      if (line.toLowerCase().startsWith('autonumber')) continue;

      if (line.toLowerCase().startsWith('title ')) {
        title = line.substring(6).trim();
        continue;
      }

      // participant Alice or actor Bob as Robert
      final partMatch = RegExp(r'^(?:participant|actor)\s+([A-Za-z0-9_]+)(?:\s+as\s+(.+))?', caseSensitive: false).firstMatch(line);
      if (partMatch != null) {
        final name = partMatch.group(2) ?? partMatch.group(1)!;
        participants.add(name.trim());
        continue;
      }

      // Messages: From->>To: text or From-->>To: text or From->To: text
      final msgMatch = RegExp(r'^([A-Za-z0-9_]+)\s*(-{1,2}>>?|-->>?|-x|--x)\s*([A-Za-z0-9_]+)\s*:\s*(.*)$').firstMatch(line);
      if (msgMatch != null) {
        final from = msgMatch.group(1)!.trim();
        final arrow = msgMatch.group(2)!;
        final to = msgMatch.group(3)!.trim();
        final text = msgMatch.group(4)!.trim();

        participants.add(from);
        participants.add(to);
        messages.add(MermaidSequenceMessage(
          from: from,
          to: to,
          text: text,
          isDashed: arrow.startsWith('--'),
        ));
      }
    }

    if (participants.isEmpty && messages.isEmpty) {
      return ParsedMermaidDiagram(
        type: MermaidDiagramType.sequence,
        rawCode: rawCode,
        parseError: 'No participants or interactions found',
      );
    }

    return ParsedMermaidDiagram(
      type: MermaidDiagramType.sequence,
      rawCode: rawCode,
      title: title,
      participants: participants.toList(),
      sequenceMessages: messages,
    );
  }

  static ParsedMermaidDiagram _parseFlowchart(String rawCode, List<String> lines) {
    String direction = 'TD';
    final nodeMap = <String, MermaidNode>{};
    final edges = <MermaidEdge>[];

    // Read header line for direction (TD, TB, BT, LR, RL)
    final header = lines.first;
    final dirMatch = RegExp(r'(?:graph|flowchart)\s+([A-Za-z]{2})', caseSensitive: false).firstMatch(header);
    if (dirMatch != null) {
      direction = dirMatch.group(1)!.toUpperCase();
      if (direction == 'TB') direction = 'TD';
    }

    // Process all lines
    for (int i = 0; i < lines.length; i++) {
      var line = lines[i];
      if (i == 0 && (line.toLowerCase().startsWith('graph') || line.toLowerCase().startsWith('flowchart'))) {
        continue;
      }
      if (line.startsWith('subgraph') || line == 'end') continue;
      if (line.startsWith('style ') || line.startsWith('classDef ') || line.startsWith('class ')) continue;

      // Handle statements separated by semicolons
      final statements = line.split(';').map((s) => s.trim()).where((s) => s.isNotEmpty);

      for (final stmt in statements) {
        _parseFlowchartStatement(stmt, nodeMap, edges);
      }
    }

    if (nodeMap.isEmpty && edges.isEmpty) {
      return ParsedMermaidDiagram(
        type: MermaidDiagramType.flowchart,
        rawCode: rawCode,
        parseError: 'Could not extract nodes or edges from flowchart',
      );
    }

    return ParsedMermaidDiagram(
      type: MermaidDiagramType.flowchart,
      rawCode: rawCode,
      direction: direction,
      nodes: nodeMap.values.toList(),
      edges: edges,
    );
  }

  static void _parseFlowchartStatement(
    String stmt,
    Map<String, MermaidNode> nodeMap,
    List<MermaidEdge> edges,
  ) {
    // Edge patterns:
    // A -->|label| B
    // A -- label --> B
    // A -.-> B
    // A ==> B
    // A --> B
    // A --- B
    final edgeRegex = RegExp(
      r'(-->\|.*?\||--\s*.*?\s*-->|==>\|.*?\||==>|-->|-\.->|---|---.*?---)',
    );

    final edgeMatch = edgeRegex.firstMatch(stmt);
    if (edgeMatch != null) {
      final leftPart = stmt.substring(0, edgeMatch.start).trim();
      final edgeOp = edgeMatch.group(0)!;
      final rightPart = stmt.substring(edgeMatch.end).trim();

      String? edgeLabel;
      bool isDotted = edgeOp.contains('-.');
      bool isThick = edgeOp.contains('==');

      if (edgeOp.startsWith('-->|') && edgeOp.endsWith('|') && edgeOp.length > 5) {
        edgeLabel = edgeOp.substring(4, edgeOp.length - 1).trim();
      } else if (edgeOp.startsWith('==>|') && edgeOp.endsWith('|') && edgeOp.length > 5) {
        edgeLabel = edgeOp.substring(4, edgeOp.length - 1).trim();
      } else if (edgeOp.startsWith('--') && edgeOp.endsWith('-->') && edgeOp.length > 5) {
        edgeLabel = edgeOp.substring(2, edgeOp.length - 3).trim();
      }

      final fromNode = _extractNode(leftPart, nodeMap);
      // The right part could also be chained (e.g. B --> C)
      if (edgeRegex.hasMatch(rightPart)) {
        // Recursive handling for chain
        final firstRightNodeMatch = RegExp(r'^([^-\s=>]+(?:\[.*?\]|\(.*?\)|<.*?>|\{.*?\}|\([\[(].*?[\])]\))?)').firstMatch(rightPart);
        if (firstRightNodeMatch != null) {
          final toNodeToken = firstRightNodeMatch.group(1)!.trim();
          final toNode = _extractNode(toNodeToken, nodeMap);
          if (fromNode != null && toNode != null) {
            edges.add(MermaidEdge(
              fromId: fromNode.id,
              toId: toNode.id,
              label: edgeLabel,
              isDotted: isDotted,
              isThick: isThick,
            ));
          }
          // Process remainder of chain
          _parseFlowchartStatement(rightPart, nodeMap, edges);
          return;
        }
      }

      final toNode = _extractNode(rightPart, nodeMap);
      if (fromNode != null && toNode != null) {
        edges.add(MermaidEdge(
          fromId: fromNode.id,
          toId: toNode.id,
          label: edgeLabel,
          isDotted: isDotted,
          isThick: isThick,
        ));
      }
    } else {
      // Standalone node definition: e.g. A[Start process]
      _extractNode(stmt, nodeMap);
    }
  }

  static MermaidNode? _extractNode(String token, Map<String, MermaidNode> nodeMap) {
    var raw = token.trim();
    if (raw.isEmpty) return null;

    // Remove trailing semicolons or punctuation
    if (raw.endsWith(';')) raw = raw.substring(0, raw.length - 1).trim();

    // 1. Pill shape: A([text])
    var m = RegExp(r'^([A-Za-z0-9_]+)\s*\(\[\s*(.*?)\s*\]\)$').firstMatch(raw);
    if (m != null) {
      final id = m.group(1)!;
      final label = m.group(2)!.trim();
      final node = MermaidNode(id: id, label: label, shape: MermaidNodeShape.pill);
      nodeMap[id] = node;
      return node;
    }

    // 2. Database/Cylinder shape: A[(text)]
    m = RegExp(r'^([A-Za-z0-9_]+)\s*\[\(\s*(.*?)\s*\)\]$').firstMatch(raw);
    if (m != null) {
      final id = m.group(1)!;
      final label = m.group(2)!.trim();
      final node = MermaidNode(id: id, label: label, shape: MermaidNodeShape.database);
      nodeMap[id] = node;
      return node;
    }

    // 3. Circle shape: A((text))
    m = RegExp(r'^([A-Za-z0-9_]+)\s*\(\(\s*(.*?)\s*\)\)$').firstMatch(raw);
    if (m != null) {
      final id = m.group(1)!;
      final label = m.group(2)!.trim();
      final node = MermaidNode(id: id, label: label, shape: MermaidNodeShape.circle);
      nodeMap[id] = node;
      return node;
    }

    // 4. Decision Diamond shape: A{text}
    m = RegExp(r'^([A-Za-z0-9_]+)\s*\{\s*(.*?)\s*\}$').firstMatch(raw);
    if (m != null) {
      final id = m.group(1)!;
      final label = m.group(2)!.trim();
      final node = MermaidNode(id: id, label: label, shape: MermaidNodeShape.decision);
      nodeMap[id] = node;
      return node;
    }

    // 5. Rounded rect shape: A(text)
    m = RegExp(r'^([A-Za-z0-9_]+)\s*\(\s*(.*?)\s*\)$').firstMatch(raw);
    if (m != null) {
      final id = m.group(1)!;
      final label = m.group(2)!.trim();
      final node = MermaidNode(id: id, label: label, shape: MermaidNodeShape.rounded);
      nodeMap[id] = node;
      return node;
    }

    // 6. Process/Rect shape: A[text]
    m = RegExp(r'^([A-Za-z0-9_]+)\s*\[\s*(.*?)\s*\]$').firstMatch(raw);
    if (m != null) {
      final id = m.group(1)!;
      final label = m.group(2)!.trim();
      final node = MermaidNode(id: id, label: label, shape: MermaidNodeShape.process);
      nodeMap[id] = node;
      return node;
    }

    // 7. Plain identifier without brackets: A
    final plainMatch = RegExp(r'^([A-Za-z0-9_]+)$').firstMatch(raw);
    if (plainMatch != null) {
      final id = plainMatch.group(1)!;
      if (!nodeMap.containsKey(id)) {
        nodeMap[id] = MermaidNode(id: id, label: id, shape: MermaidNodeShape.process);
      }
      return nodeMap[id];
    }

    return null;
  }
}
